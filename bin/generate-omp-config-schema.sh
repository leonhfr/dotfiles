#!/bin/sh
set -eu

profile=${OMP_PROFILE:-personal}
version=$(omp --version)

omp --profile "$profile" config list --json | jq --arg version "$version" '
  def leaf($setting):
    ({
      type: (
        if $setting.type == "enum" then "string"
        elif $setting.type == "record" then "object"
        else $setting.type
        end
      )
    }
    + (if $setting.description != "" then {description: $setting.description} else {} end)
    + (if $setting.type == "array" then {items: {}} else {} end)
    + (if $setting.type == "record" then {additionalProperties: true} else {} end));

  def setting_path($key):
    reduce ($key | split(".")[]) as $part ([]; . + ["properties", $part]);

  def close_namespaces:
    if type == "object" and has("properties") then
      .type = "object"
      | .additionalProperties = false
      | .properties |= with_entries(.value |= close_namespaces)
    else
      .
    end;

  reduce to_entries[] as $entry (
    {
      "$schema": "https://json-schema.org/draft/2020-12/schema",
      "$comment": "Generated by bin/generate-omp-config-schema.sh with \($version). Run mise run omp-schema after upgrading OMP.",
      title: "Oh My Pi configuration",
      description: "Partial or complete OMP config.yml settings.",
      type: "object",
      properties: {},
      additionalProperties: false
    };
    setpath(setting_path($entry.key); leaf($entry.value))
  )
  | close_namespaces
'
